/**
 * The client source. lang 'ts': one TypeScript file. lang 'js': { js, dts } for projects
 * without TypeScript (the types still reach editors through the .d.ts).
 */
export function generateClient(doc, { lang = 'ts', prefix = '/api' } = {}) {
  const ops = clientOperations(doc, { prefix });
  const groups = new Map();
  for (const op of ops) {
    if (!groups.has(op.group)) groups.set(op.group, []);
    groups.get(op.group).push(op);
  }

  // Types: the document's schemas, a query type per operation that has query parameters.
  const types = [];
  for (const [name, schema] of Object.entries(doc.components?.schemas ?? {})) {
    if (name === 'Error') continue;
    types.push(`export type ${pascal(name)} = ${tsType(schema)};`);
  }
  types.push(
    `export interface ApiErrorBody {\n  error: { code: string; message: string; details?: Record<string, string>; requestId?: string };\n}`,
    `export interface PageMeta {\n  total: number;\n  page: number;\n  limit: number;\n  pages: number;\n}`,
    `export interface Page<T> {\n  data: T[];\n  meta: PageMeta;\n}`,
    `export interface RequestOptions {\n  /** Abort the request (AbortController). */\n  signal?: AbortSignal;\n  headers?: Record<string, string>;\n}`,
    `export interface ClientOptions {
  /** Where the API runs, e.g. http://localhost:5001 (default: same origin). */
  baseUrl?: string;
  /** The session token from auth.login / auth.register, or a function returning it. Sent as Authorization: Bearer. */
  token?: string | null | (() => string | null | undefined | Promise<string | null | undefined>);
  /** Another fetch (React Native, tests, retries). */
  fetch?: (input: string, init: any) => Promise<{ ok: boolean; status: number; text(): Promise<string> }>;
  headers?: Record<string, string>;
  /** fetch credentials mode, e.g. 'include' for cookies across origins. */
  credentials?: 'omit' | 'same-origin' | 'include';
  /** Called with the error when the API answers 401 (session expired): sign out, redirect... */
  onUnauthorized?: (error: CalmApiError) => void | Promise<void>;
}`,
  );
  const queryType = (op) => `${pascal(op.operationId ?? `${op.group} ${op.name}`)}Query`;
  for (const op of ops) {
    if (!op.query.length) continue;
    const props = op.query.map((q) => {
      const doc = q.description ? `  /** ${q.description.replace(/\*\//g, '* /')} */\n` : '';
      return `${doc}  ${prop(q.name)}?: ${tsType(q.schema)}${q.schema?.type === 'string' ? '' : ' | string'};`;
    });
    types.push(`export interface ${queryType(op)} {\n${props.join('\n')}\n  [filter: string]: string | number | boolean | undefined;\n}`);
  }

  // Signatures (the CalmClient interface) and the implementation, built from the same list.
  const sig = (op) => {
    const args = op.params.map((name) => `${camel(name)}: string`);
    if (op.body) args.push(`body${op.bodyRequired ? '' : '?'}: ${tsType(op.body, { indent: '    ' })}`);
    if (op.query.length) args.push(`query?: ${queryType(op)}`);
    args.push('options?: RequestOptions');
    return `(${args.join(', ')}) => Promise<${op.result}>`;
  };
  const docComment = (op, indent) => `${indent}/** ${[op.summary, `\`${op.method} ${op.path}\``, op.access ? `Access: ${op.access}.` : null].filter(Boolean).join(' ').replace(/\*\//g, '* /')} */\n`;
  const iface = [...groups].map(([group, list]) => `  ${prop(group)}: {\n${list.map((op) => `${docComment(op, '    ')}    ${prop(op.name)}: ${sig(op)};`).join('\n')}\n  };`);
  const clientType = `export interface CalmClient {\n  /** Replace the token (after sign-in or sign-out). */\n  setToken(token: ClientOptions['token']): void;\n  /** Any request, for routes added after this file was generated. */\n  request(method: string, path: string, input: { body?: unknown; query?: Record<string, unknown>; unwrap?: boolean }, options?: RequestOptions): Promise<any>;\n${iface.join('\n')}\n}`;

  const impl = [...groups].map(([group, list]) => {
    const fns = list.map((op) => {
      const args = op.params.map((n) => camel(n));
      if (op.body) args.push('body');
      if (op.query.length) args.push('query');
      args.push('options');
      const path = op.path.replace(/\{([^}]+)\}/g, (_, n) => `\${p(${camel(n)})}`);
      const input = [op.body ? 'body' : null, op.query.length ? 'query' : null, op.unwrap ? 'unwrap: true' : null].filter(Boolean).join(', ');
      return `    ${prop(op.name)}: (${args.map((a) => `${a}‹: any›`).join(', ')}) => request('${op.method}', \`${path}\`, { ${input} }, options),`;
    });
    return `  client[${JSON.stringify(group)}] = {\n${fns.join('\n')}\n  };`;
  });
  const runtime = `${RUNTIME}${impl.join('\n')}\n  return client;\n}\n`;
  const info = doc.info ?? { title: 'API', version: '' };

  if (lang === 'ts') return `${HEADER(info)}\n${types.join('\n\n')}\n\n${clientType}\n${runtime.replace(/‹([^›]*)›/g, '$1')}`;
  const js = `${HEADER(info)}// Types: calm-client.d.ts next to this file.\n${runtime.replace(/‹[^›]*›/g, '')}`;
  const dts = `${HEADER(info)}\n${types.join('\n\n')}\n\n${clientType}\n\nexport declare class CalmApiError extends Error {\n  status: number;\n  code: string;\n  details: Record<string, string> | undefined;\n  requestId: string | undefined;\n  body: unknown;\n  constructor(status: number, body: unknown);\n}\n\nexport declare function createClient(options?: ClientOptions): CalmClient;\n`;
  return { js, dts };
}

/**
 * calm dev with client: { out } in calm.config.js: write the client again after every start, so the
 * frontend's types follow the API while you work. Unchanged files are not touched.
 */
export function writeClientFile(app) {
  const out = app.config.client?.out;
  if (!out) return null;
  const file = resolve(app.root, out);
  const lang = /\.m?js$/.test(file) ? 'js' : 'ts';
  const code = generateClient(app.openapi(), { lang, prefix: app.config.apiPrefix });
  const files = lang === 'ts' ? [[file, code]] : [[file, code.js], [file.replace(/\.m?js$/, '.d.ts'), code.dts]];
  mkdirSync(dirname(file), { recursive: true });
  let changed = false;
  for (const [path, text] of files) {
    if (existsSync(path) && readFileSync(path, 'utf8') === text) continue;
    writeFileSync(path, text);
    changed = true;
  }
  return { file, changed };
}
