// The exposure budget: who may do what, written down in security.snapshot.json at the project
// root and committed. Access can then only widen on purpose: any cell of the exposure matrix
// that is more permissive than the snapshot is a doctor error (so `calm doctor --ci` and
// `calm audit --ci` fail) until a person accepts it with `calm audit --accept --reason "..."`,
// which records who, when and why in the same file.
//
// The file doubles as the plain-text answer to "who can see what" for anyone who asks.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const BUDGET_FILE = 'security.snapshot.json';
const RANK = { off: 0, never: 0, deny: 0, no: 0, own: 1, custom: 1, allow: 2, yes: 2 };
const LABEL = { off: 'off', never: 'never', deny: 'no', no: 'no', own: 'own records', custom: 'custom rule', allow: 'yes', yes: 'yes' };

/** Flatten a matrix into cells: "post list anonymous" -> "allow", "user.email read user" -> "yes". */
export function matrixCells(matrix) {
  const cells = new Map();
  for (const r of matrix?.resources ?? []) {
    for (const [action, byPersona] of Object.entries(r.actions ?? {})) {
      for (const [persona, value] of Object.entries(byPersona)) cells.set(`${r.name} ${action} ${persona}`, value);
    }
    for (const f of r.fields ?? []) {
      for (const [persona, value] of Object.entries(f.read ?? {})) cells.set(`${r.name}.${f.name} read ${persona}`, value);
      for (const [persona, value] of Object.entries(f.write ?? {})) cells.set(`${r.name}.${f.name} write ${persona}`, value);
    }
  }
  return cells;
}

/** The matrix as stored: stable, small, readable. */
export function compactMatrix(matrix) {
  return {
    personas: matrix.personas.map((p) => p.key ?? p),
    resources: matrix.resources.map((r) => ({
      name: r.name,
      path: r.path,
      actions: r.actions,
      fields: Object.fromEntries(r.fields.map((f) => [f.name, { read: f.read, write: f.write, ...(f.pii ? { pii: true } : {}) }])),
    })),
  };
}

const expand = (stored) => ({
  resources: (stored?.resources ?? []).map((r) => ({ ...r, fields: Object.entries(r.fields ?? {}).map(([name, f]) => ({ name, ...f })) })),
});

/** Cells now more permissive than the snapshot (a cell that did not exist counts as no access). */
export function compareBudget(stored, current) {
  const before = matrixCells(expand(stored));
  const after = matrixCells(current);
  const wider = [];
  const narrower = [];
  for (const [cell, value] of after) {
    const old = before.get(cell);
    const a = RANK[old] ?? 0;
    const b = RANK[value] ?? 0;
    if (b > a || (old !== undefined && value === 'custom' && old !== 'custom')) wider.push({ cell, before: old ?? null, after: value, text: `${cell}: ${old === undefined ? 'new' : LABEL[old] ?? old} -> ${LABEL[value] ?? value}` });
    else if (b < a) narrower.push({ cell, before: old, after: value });
  }
  for (const [cell, value] of before) if (!after.has(cell) && (RANK[value] ?? 0) > 0) narrower.push({ cell, before: value, after: null });
  return { wider, narrower };
}

export function readBudget(root) {
  const file = join(root, BUDGET_FILE);
  if (!existsSync(file)) return null;
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (err) {
    return { error: `${BUDGET_FILE} is not valid JSON: ${err.message}` };
  }
}

/**
 * Accept the current matrix. `by` is a person; `reason` says why access changed.
 * Returns { budget, wider } where wider lists the cells this acceptance widened.
 */
export function acceptBudget(root, current, { by, reason = null, now = new Date() } = {}) {
  if (!by?.name) throw new Error('An exposure budget is accepted by a person: give a name (git config user.name, or --as "Name <email>")');
  const previous = readBudget(root);
  const wider = previous && !previous.error ? compareBudget(previous.matrix, current).wider : [];
  if (previous && !previous.error && wider.length && !(typeof reason === 'string' && reason.trim())) {
    throw new Error(`Access widens in ${wider.length} place${wider.length === 1 ? '' : 's'}: say why with --reason "..." (it is recorded next to your name)`);
  }
  const accepted = [...(previous?.accepted ?? [])];
  accepted.push({
    by: { name: by.name, email: by.email ?? null },
    at: now.toISOString(),
    reason: typeof reason === 'string' && reason.trim() ? reason.trim().slice(0, 1000) : previous ? null : 'first snapshot',
    widened: wider.map((w) => w.text),
  });
  const budget = {
    $comment: 'Who may do what in this API. Generated by calm audit --accept; CI fails when access widens beyond it. Commit it.',
    version: 1,
    updatedAt: now.toISOString(),
    matrix: compactMatrix(current),
    accepted: accepted.slice(-50),
  };
  writeFileSync(join(root, BUDGET_FILE), `${JSON.stringify(budget, null, 2)}\n`);
  return { budget, wider };
}

/** Doctor findings: an error per widened cell group, when a snapshot exists. */
export function budgetFindings(root, current) {
  const budget = readBudget(root);
  if (!budget) return [];
  if (budget.error) return [{ level: 'error', id: 'exposure-budget', title: budget.error, file: BUDGET_FILE }];
  const { wider } = compareBudget(budget.matrix, current);
  if (!wider.length) return [];
  return [{
    level: 'error',
    id: 'exposure-budget',
    title: `Access widened beyond security.snapshot.json in ${wider.length} place${wider.length === 1 ? '' : 's'}`,
    detail: `${wider.slice(0, 20).map((w) => w.text).join('\n')}${wider.length > 20 ? `\n...and ${wider.length - 20} more` : ''}\nIf it is intended: npx calm audit --accept --reason "why". Otherwise fix the policy or field rule.`,
    file: BUDGET_FILE,
  }];
}
